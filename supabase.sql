create table if not exists public.readings (
  id bigint generated by default as identity primary key,
  device_id text not null,
  ph numeric(5,2) not null check (ph between 0 and 14),
  temperature numeric(5,2) not null check (temperature between -55 and 125),
  sensor1 boolean not null,
  sensor2 boolean not null,
  water_level text not null check (water_level in ('LOW','MIDDLE','HIGH','SENSOR ERROR')),
  created_at timestamptz not null default now()
);

create index if not exists readings_created_at_idx
  on public.readings (created_at desc);

alter table public.readings enable row level security;

-- No public policies are created. Vercel accesses this table using the
-- server-only service role key; browsers and ESP32 never receive that key.
